/// Width in terminal columns of a banner for this text.
pub fn width(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 { 0 } else { n * 6 }
}

/// Build the pixel grid for a banner with a drop shadow.
pub fn grid(text: &str, color: Rgb) -> Grid {
    let w = width(text);
    let h = 8;
    let mut g: Grid = vec![vec![None; w]; h];
    let shadow = theme::shade(color, 0.32);
    for (i, ch) in text.chars().enumerate() {
        let rows = glyph(ch);
        for (y, row) in rows.iter().enumerate() {
            for (x, px) in row.chars().enumerate() {
                if px != '#' {
                    continue;
                }
                let gx = i * 6 + x;
                if gx + 1 < w && y + 1 < h && g[y + 1][gx + 1].is_none() {
                    g[y + 1][gx + 1] = Some(shadow);
                }
                g[y][gx] = Some(color);
            }
        }
    }
    g
}

pub fn banner(text: &str, color: Rgb, tint: Tint) -> Vec<Line<'static>> {
    grid_lines(&grid(text, color), tint)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn banner_is_four_rows_and_sized() {
        let lines = banner("DEADLINE", (255, 255, 255), Tint::None);
        assert_eq!(lines.len(), 4);
        assert_eq!(width("DEADLINE"), 48);
        for l in &lines {
            assert_eq!(l.width(), 48);
        }
    }
}
